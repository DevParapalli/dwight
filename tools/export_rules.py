"""Write the rulebook: every rule the agent now applies without asking.

A change batch runs with the model off, so these are the only rules it has. The
rulebook is that set written down for a person to read and sign off: the column
mappings accepted per export, the decisions people made, the value
normalisations learned, and the policy in force.

Usage:
    uv run python tools/export_rules.py --db data/dwight.db --out rules/RULEBOOK.md
"""

import argparse
import hashlib
import json
import sqlite3
import sys
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from app.agent.clean import clean_string
from app.ingest.readers import load_source_table
from app.schema.loader import load_schema


def _cell(v) -> str:
    return str(v if v is not None else "").replace("|", "\\|").replace("\n", " ")


def _table(headers: list[str], rows: list[list]) -> list[str]:
    if not rows:
        return ["None yet.", ""]
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return out + [""]


def _normalisations(conn, mappings, schema_path: Path) -> list[list]:
    """The value cache is keyed by a hash of field and raw value, so the raw
    values are read back from the newest run's copy of each export and hashed
    the same way normalize_llm does."""
    enum_fields = {n for n, f in load_schema(schema_path).fields.items() if f.type == "enum"}
    out, seen = [], set()
    for m in mappings:
        if m["target_field"] not in enum_fields:
            continue
        latest = conn.execute(
            "SELECT run_id FROM source_files WHERE filename = ? ORDER BY created_at DESC LIMIT 1",
            (m["filename"],)).fetchone()
        path = Path("data/runs") / latest["run_id"] / m["filename"]
        if not path.exists():
            continue
        raws = {clean_string(r.get(m["column_name"])) for r in load_source_table(path).rows()}
        for raw in sorted(r for r in raws if r):
            key = hashlib.sha256(f"value_norm:{m['target_field']}:{raw}".encode()).hexdigest()
            row = conn.execute("SELECT model, response FROM llm_cache WHERE prompt_hash = ?", (key,)).fetchone()
            if row is None or (m["target_field"], raw) in seen:
                continue
            seen.add((m["target_field"], raw))
            response = json.loads(row["response"])
            if response.get("value"):
                out.append([m["target_field"], raw, response["value"],
                            f"{response.get('confidence', 0):.2f}", row["model"]])
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", type=Path, default=Path("data/dwight.db"))
    parser.add_argument("--schema", type=Path, default=Path("schemas/employee.v1.yaml"))
    parser.add_argument("--policy", type=Path, default=Path("policy/escalation.yaml"))
    parser.add_argument("--out", type=Path, default=Path("rules/RULEBOOK.md"))
    args = parser.parse_args()
    if not args.db.exists():
        raise SystemExit(f"{args.db} does not exist; run the agent first")

    conn = sqlite3.connect(args.db)
    conn.row_factory = sqlite3.Row

    # The newest accepted mapping per export and column is the one learned_mapping applies.
    mappings = conn.execute(
        """SELECT sf.filename, sc.name AS column_name, m.target_field, MAX(m.created_at) AS since
           FROM mappings m
           JOIN source_columns sc ON sc.id = m.source_column_id
           JOIN source_files sf ON sf.id = sc.source_file_id
           WHERE m.status IN ('accepted', 'overridden')
           GROUP BY sf.filename, sc.name ORDER BY sf.filename, sc.name"""
    ).fetchall()

    # A decision is keyed by a hash; the question it answered is the readable form.
    decisions = conn.execute(
        """SELECT d.reason_code, d.resolution, d.resolved_by, d.created_at,
                  (SELECT e.question FROM escalations e
                   WHERE e.reason_code = d.reason_code AND e.signature = d.signature
                   ORDER BY e.created_at DESC LIMIT 1) AS question
           FROM decisions d ORDER BY d.reason_code, d.created_at"""
    ).fetchall()

    normalisations = _normalisations(conn, mappings, args.schema)

    lines = [
        "# Rulebook",
        "",
        (f"Exported {datetime.now(UTC):%Y-%m-%d %H:%M} UTC from `{args.db}`. "
         "Generated by `just rules`; do not edit by hand."),
        "",
        "## Mappings",
        "",
        "Accepted on an earlier batch of the same export, and applied to every later one.",
        "",
        *_table(["Export", "Column", "Field", "Since"],
                [[m["filename"], m["column_name"], m["target_field"] or "(left out)", m["since"]]
                 for m in mappings]),
        "## Decisions",
        "",
        "Answers people gave in the queue. Learnable ones are applied without asking again.",
        "",
        *_table(["Reason code", "Question", "Answer", "Value", "By", "When"],
                [[d["reason_code"], d["question"] or "", json.loads(d["resolution"]).get("action"),
                  json.loads(d["resolution"]).get("value") or "", d["resolved_by"], d["created_at"]]
                 for d in decisions]),
        "## Learned normalisations",
        "",
        "Source values the model mapped to an allowed value, cached and reused with the model off.",
        "",
        *_table(["Field", "Source value", "Read as", "Confidence", "Model"], normalisations),
        "## Policy",
        "",
        f"From `{args.policy}`.",
        "",
        "```yaml",
        args.policy.read_text().rstrip(),
        "```",
        "",
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))
    print(f"wrote {args.out}: {len(mappings)} mappings, {len(decisions)} decisions, "
          f"{len(normalisations)} normalisations")


if __name__ == "__main__":
    main()
